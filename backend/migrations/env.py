"""Alembic environment: async migrations with the willay_owner role.

Migrations are hand-written explicit SQL (ADR-0006): TimescaleDB and PostGIS DDL cannot be
autogenerated, so there is no `target_metadata`.
"""

import asyncio
import os
from logging.config import fileConfig

from alembic import context
from sqlalchemy.engine import Connection
from sqlalchemy.ext.asyncio import create_async_engine

config = context.config
if config.config_file_name is not None:
    fileConfig(config.config_file_name)


def _database_url() -> str:
    url = os.environ.get("WILLAY_MIGRATE_DATABASE_URL")
    if not url:
        raise RuntimeError("WILLAY_MIGRATE_DATABASE_URL is missing (the willay_owner URL)")
    return url


def run_migrations_offline() -> None:
    context.configure(url=_database_url(), literal_binds=True)
    with context.begin_transaction():
        context.run_migrations()


def _run_sync(connection: Connection) -> None:
    # transaction_per_migration: if 0003 fails, 0001 and 0002 stay applied.
    context.configure(connection=connection, transaction_per_migration=True)
    with context.begin_transaction():
        context.run_migrations()


async def run_migrations_online() -> None:
    engine = create_async_engine(_database_url())
    async with engine.connect() as connection:
        await connection.run_sync(_run_sync)
    await engine.dispose()


if context.is_offline_mode():
    run_migrations_offline()
else:
    asyncio.run(run_migrations_online())
